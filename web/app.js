const $ = (q) => document.querySelector(q);
const $$ = (q) => [...document.querySelectorAll(q)];
const state = { manifest: null, sample: null, epoch: 0, layer: 1, channel: 0,
  mode: 'original', info: null, trajectory: null, timer: null, requestId: 0,
  samples: [], pinned: null };
